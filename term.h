#define return_defer(Result) do { result = (Result); goto defer; } while (0)

#define TERM_MIN_COLUMNS   (40)
#define TERM_MIN_ROWS      (13)
#define TERM_MAX_COLUMNS   (256)
#define TERM_MAX_ROWS      (256)

#define TERM_HISTORY_POW_2 (11)
#define TERM_HISTORY_COUNT (1 << TERM_HISTORY_POW_2)
#define TERM_HISTORY_MASK  (TERM_HISTORY_COUNT - 1)

#define TERM_GLYPH_WIDTH   (10)
#define TERM_GLYPH_HEIGHT  (16)
#define TERM_ATLAS_COLUMNS (16)
#define TERM_ATLAS_ROWS    (4)
#define TERM_ATLAS_WIDTH   (TERM_ATLAS_COLUMNS * TERM_GLYPH_WIDTH)
#define TERM_ATLAS_HEIGHT  (TERM_ATLAS_ROWS * TERM_GLYPH_HEIGHT)

typedef enum term_color {
    TERM_COLOR_BLACK,
    TERM_COLOR_RED,
    TERM_COLOR_GREEN,
    TERM_COLOR_YELLOW,
    TERM_COLOR_BLUE,
    TERM_COLOR_MAGENTA,
    TERM_COLOR_CYAN,
    TERM_COLOR_WHITE,
    TERM_COLOR_BRIGHT_BLACK,
    TERM_COLOR_BRIGHT_RED,
    TERM_COLOR_BRIGHT_GREEN,
    TERM_COLOR_BRIGHT_YELLOW,
    TERM_COLOR_BRIGHT_BLUE,
    TERM_COLOR_BRIGHT_MAGENTA,
    TERM_COLOR_BRIGHT_CYAN,
    TERM_COLOR_BRIGHT_WHITE,
} term_color;

typedef enum term_style {
    TERM_STYLE_NONE = 0,
    TERM_STYLE_BOLD = 1 << 0,
    TERM_STYLE_UNDERLINE = 1 << 1,
    TERM_STYLE_STRIKETHRU = 1 << 2,
    TERM_STYLE_INVERT = 1 << 3,
} term_style;

typedef struct term_cell {
    uint8_t c;
    uint8_t fg, bg;
    uint8_t style;
} term_cell;

typedef struct term_lines {
    term_cell* cell_data;
    uint64_t wrap_flags[TERM_HISTORY_COUNT / sizeof(uint64_t)];
    uint32_t next_index, count;
    uint32_t cursor_line_index;
    uint16_t cursor_column;
    uint16_t column_count;
} term_lines;

typedef struct term_vertex {
    uint8_t x, y;
    uint8_t tx, ty;
    uint8_t fr, fg, fb;
    uint8_t br, bg, bb;
    uint8_t c;
} term_vertex;

typedef struct term {
    term_lines lines;

    GLFWwindow* window;
    bool is_fullscreen;
    int cached_window_width, cached_window_height;

    int aspect;
    int columns, rows;

    GLuint font_atlas;
    GLuint vbo, ibo;
    GLuint vertex_shader, fragment_shader;
    GLuint shader_program;
    GLuint uniform_glyph_size, uniform_atlas_size;
    GLuint uniform_viewport_size, uniform_glyph_aspect;

    term_vertex* vertices;
    bool dirty;
} term;

bool term_lines_init(term_lines* lines, uint16_t column_count);
void term_lines_deinit(term_lines* lines);
term_cell* term_lines_get_cells_at_index(const term_lines* lines, uint32_t index);
bool term_lines_reflow(term_lines* lines, uint16_t new_column_count);

bool term_init(term* t);
void term_deinit(term* t);
void term_loop(term* t);
bool term_flush(term* t);
void term_putc(term* t, char c);
void term_puts(term* t, const char* str);
void term_printf(term* t, const char* format, ...);

